import { chromium } from 'playwright-core';
import fs from 'node:fs';
const exe = fs.readdirSync('/opt/pw-browsers').filter(d => d.startsWith('chromium-')).map(d => `/opt/pw-browsers/${d}/chrome-linux/chrome`).find(p => fs.existsSync(p));
const b = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', e => console.log('pageerror:', e.message));
p.on('console', m => { if (m.type() === 'error') console.log('console.error:', m.text()); });
await p.goto(process.env.MJ_URL);
await p.waitForTimeout(1500);
const out = process.env.OUT || '/tmp/shots';
await p.screenshot({ path: `${out}/chat.png` });
await p.click('[data-view=settings]'); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/settings.png` });
await p.click('[data-view=skills]'); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/skills.png` });
await p.click('[data-view=mcp]'); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/mcp.png` });
await p.click('[data-view=history]'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/history.png` });
await p.click('[data-view=chat]'); await p.keyboard.press('Control+k'); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/palette.png` });
await b.close();
